#!/usr/bin/env python3
"""Render PROGRESS.md from the project knowledge graph.

Reads memory/project-graph.jsonl (MCP memory server format) and writes
PROGRESS.md with: overall %, per-phase and per-person progress, a Mermaid
dependency graph coloured by status, blocked tasks and what is ready to start.

Status is the LAST observation on a Task that starts with "status:"
(todo | in_progress | blocked | done).

Usage:  python scripts/progress.py [--today YYYY-MM-DD]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRAPH = ROOT / "memory" / "project-graph.jsonl"
OUT = ROOT / "PROGRESS.md"
WEIGHT = {"todo": 0.0, "blocked": 0.0, "in_progress": 0.5, "done": 1.0}
ICON = {"todo": "⬜", "in_progress": "🟨", "blocked": "🟥", "done": "✅"}


def load():
    entities, relations = {}, []
    for line in GRAPH.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        obj = json.loads(line)
        if obj.get("type") == "entity":
            entities[obj["name"]] = obj
        elif obj.get("type") == "relation":
            relations.append(obj)
    return entities, relations


def obs(entity: dict, key: str, default: str = "") -> str:
    vals = [o.split(":", 1)[1].strip() for o in entity.get("observations", []) if o.lower().startswith(key + ":")]
    return vals[-1] if vals else default


def status_of(entity: dict) -> str:
    raw = obs(entity, "status", "todo").lower()
    for s in ("in_progress", "blocked", "done", "todo"):
        if raw.startswith(s):
            return s
    return "todo"


def bar(frac: float, width: int = 20) -> str:
    n = round(frac * width)
    return "█" * n + "░" * (width - n) + f" {frac * 100:4.0f}%"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--today", default=dt.date.today().isoformat())
    args = ap.parse_args()
    today = dt.date.fromisoformat(args.today)

    ents, rels = load()
    tasks = {n: e for n, e in ents.items() if e["entityType"] == "Task"}
    phases = {n: e for n, e in ents.items() if e["entityType"] == "Phase"}
    phase_of, owners, deps = {}, defaultdict(list), defaultdict(list)
    for r in rels:
        if r["relationType"] == "part_of" and r["from"] in tasks:
            phase_of[r["from"]] = r["to"]
        elif r["relationType"] == "owns" and r["to"] in tasks:
            owners[r["to"]].append(r["from"])
        elif r["relationType"] == "depends_on" and r["from"] in tasks:
            deps[r["from"]].append(r["to"])
    st = {t: status_of(e) for t, e in tasks.items()}

    def pct(names):
        names = list(names)
        return sum(WEIGHT[st[n]] for n in names) / len(names) if names else 0.0

    deadline = dt.date(2026, 11, 10)
    days_left = (deadline - today).days
    out = [
        "# Progress — Rex",
        "",
        f"_Generated by `scripts/progress.py` from `memory/project-graph.jsonl` on {today.isoformat()}. "
        "Do not edit by hand — update the graph and re-run._",
        "",
        f"**Overall:** `{bar(pct(tasks))}` · **Days to deadline:** {days_left} (10 Nov 2026, 23:59 IST)",
        "",
        "| Status | Count |",
        "|---|---|",
    ]
    for s in ("done", "in_progress", "blocked", "todo"):
        out.append(f"| {ICON[s]} {s} | {sum(1 for v in st.values() if v == s)} |")

    out += ["", "## By phase", "", "| Phase | Window | Progress | Gate |", "|---|---|---|---|"]
    for p in sorted(phases):
        names = [t for t in tasks if phase_of.get(t) == p]
        win = obs(phases[p], "window")
        flag = ""
        try:
            end = dt.date.fromisoformat(win.split("..")[1])
            if today > end and pct(names) < 1:
                flag = " ⚠️ late"
        except (IndexError, ValueError):
            pass
        out.append(
            f"| {p} — {obs(phases[p], 'title')} | {win} | `{bar(pct(names), 10)}`{flag} | {obs(phases[p], 'gate')} |"
        )

    out += ["", "## By person", "", "| Person | Tasks | Progress |", "|---|---|---|"]
    for person in ("Johny", "Shanky"):
        names = [t for t in tasks if person in owners[t]]
        out.append(f"| {person} | {len(names)} | `{bar(pct(names), 10)}` |")

    blocked = [t for t in sorted(tasks) if st[t] == "blocked"]
    ready = [t for t in sorted(tasks) if st[t] == "todo" and all(st.get(d) == "done" for d in deps[t])]
    doing = [t for t in sorted(tasks) if st[t] == "in_progress"]

    def line(t):
        return f"- **{t}** {obs(tasks[t], 'title')} — {', '.join(owners[t])}"

    out += ["", "## In progress", ""] + ([line(t) for t in doing] or ["- none"])
    out += ["", "## Blocked", ""] + ([line(t) + f" — {obs(tasks[t], 'status')}" for t in blocked] or ["- none"])
    out += ["", "## Ready to start (all dependencies done)", ""] + ([line(t) for t in ready] or ["- none"])

    out += ["", "## Dependency map", "", "```mermaid", "flowchart LR"]
    for s, color in (("done", "#3BC07A"), ("in_progress", "#E3A72F"), ("blocked", "#EF6262"), ("todo", "#D0D3D8")):
        out.append(f"  classDef {s} fill:{color},stroke:#555,color:#111")
    for p in sorted(phases):
        out.append(f'  subgraph {p.replace(" ", "")}["{p}"]')
        for t in sorted(x for x in tasks if phase_of.get(x) == p):
            label = obs(tasks[t], "title").replace('"', "'")[:38]
            out.append(f'    {t.replace("-", "")}["{t}: {label}"]:::{st[t]}')
        out.append("  end")
    for t in sorted(tasks):
        for d in deps[t]:
            out.append(f"  {d.replace('-', '')} --> {t.replace('-', '')}")
    out += ["```", "", "## All tasks", "", "| Task | Title | Owner | Phase | Status |", "|---|---|---|---|---|"]
    for t in sorted(tasks):
        out.append(
            f"| {t} | {obs(tasks[t], 'title')} | {', '.join(owners[t])} | {phase_of.get(t, '')} | {ICON[st[t]]} {st[t]} |"
        )
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT} — overall {pct(tasks) * 100:.0f}%")


if __name__ == "__main__":
    main()
